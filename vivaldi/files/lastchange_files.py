#!/usr/bin/env python3
#
# Write the files the lastchange hooks of gclient write from git, which the
# Vivaldi source tarball comes without, in the format of
# build/util/lastchange.py.  That script fails outside of a git checkout, so
# the revisions are the zero revision it used to fall back to.  The time is
# the one chrome/VERSION has in the tarball rather than 0, because
# compute_build_timestamp.py makes the build time of an official build out of
# LASTCHANGE.committime and the copyright year comes from LASTCHANGE.
#
# usage: lastchange_files.py CHROMIUM_DIR

import datetime
import os
import sys

ZERO_REVISION = '0' * 40


def header(path, define, version):
    guard = path.upper().replace('/', '_').replace('.', '_') + '_'
    return ('/* Generated by lastchange.py, do not edit.*/\n'
            '\n'
            '#ifndef %(guard)s\n'
            '#define %(guard)s\n'
            '\n'
            '#define %(define)s "%(version)s"\n'
            '\n'
            '#endif  // %(guard)s\n') % {
                'guard': guard, 'define': define, 'version': version}


def write(root, path, contents):
    with open(os.path.join(root, path), 'w') as f:
        f.write(contents)


def main():
    root = sys.argv[1]
    timestamp = int(os.stat(os.path.join(root, 'chrome/VERSION')).st_mtime)
    year = datetime.datetime.fromtimestamp(timestamp,
                                           datetime.timezone.utc).year

    write(root, 'build/util/LASTCHANGE',
          'LASTCHANGE=%s\nLASTCHANGE_YEAR=%d\n' % (ZERO_REVISION, year))
    write(root, 'build/util/LASTCHANGE.committime', str(timestamp))
    for path, define in (('gpu/config/gpu_lists_version.h',
                          'GPU_LISTS_VERSION'),
                         ('skia/ext/skia_commit_hash.h', 'SKIA_COMMIT_HASH'),
                         ('gpu/webgpu/dawn_commit_hash.h', 'DAWN_COMMIT_HASH')):
        write(root, path, header(path, define, ZERO_REVISION))
    write(root, 'gpu/webgpu/DAWN_VERSION', ZERO_REVISION)


if __name__ == '__main__':
    main()
